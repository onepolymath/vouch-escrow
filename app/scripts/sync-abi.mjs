// Copies the Vouch ABI out of the forge build into lib/abi.ts.
// Run `forge build` in ../contracts first.
import { readFileSync, writeFileSync } from "node:fs";

const artifact = (name) =>
  JSON.parse(
    readFileSync(new URL(`../../contracts/out/${name}.sol/${name}.json`, import.meta.url), "utf8"),
  );

const pick = (abi) => abi.filter((x) => x.type !== "constructor");

const out = `// generated by scripts/sync-abi.mjs, do not edit by hand
export const vouchAbi = ${JSON.stringify(pick(artifact("Vouch").abi))} as const;

export const mockAgentIdAbi = ${JSON.stringify(pick(artifact("MockAgentID").abi))} as const;

export const mockUsdAbi = ${JSON.stringify(pick(artifact("MockUSD").abi))} as const;
`;

writeFileSync(new URL("../lib/abi.ts", import.meta.url), out);
console.log("wrote lib/abi.ts");
